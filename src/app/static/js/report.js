// Shared by the Research Agent and Stock Insights pages: formatting, agent job polling and report rendering.
window.Centaur = (() => {
  const fmtMoney = (v, digits = 0) => v == null ? "–" : "$" + v.toLocaleString(undefined, { minimumFractionDigits: digits, maximumFractionDigits: digits });
  const fmtPrice = (v) => fmtMoney(v, 2);
  const fmtPct = (v, digits = 1) => v == null ? "–" : (v > 0 ? "+" : "") + v.toLocaleString(undefined, { maximumFractionDigits: digits, minimumFractionDigits: digits }) + "%";
  const fmtCompact = (v) => v == null ? "–" : "$" + v.toLocaleString(undefined, { notation: "compact", maximumFractionDigits: 1 });
  const fmtWhen = (iso) => iso ? new Date(iso).toLocaleString(undefined, { dateStyle: "medium", timeStyle: "short" }) : "";
  const fmtDay = (iso) => iso ? new Date(iso).toLocaleDateString(undefined, { month: "short", day: "numeric" }) : "";
  const tone = (v) => v == null ? "" : v > 0 ? "up" : v < 0 ? "down" : "";
  const escapeHtml = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const errorText = (err) => err instanceof TypeError ? "Couldn't reach the server. Is the app still running?" : err.message;
  const safeUrl = (u) => /^https?:\/\//i.test(u || "") ? u : "#";

  async function api(url, body, method = body ? "POST" : "GET") {
    const res = await fetch(url, {
      method,
      headers: body ? { "Content-Type": "application/json" } : {},
      body: body ? JSON.stringify(body) : undefined,
    });
    const data = await res.json();
    if (!res.ok) throw Object.assign(new Error(data.error || data.message || res.statusText), { status: res.status, data });
    return data;
  }

  // ---------- agent job ----------
  const POLL_MS = 3000;
  let pollTimer = null;

  function renderJob(el, s) {
    const running = s.state === "running";
    el.hidden = s.state === "idle" || s.state === "done";
    el.classList.toggle("error", s.state === "error");
    if (el.hidden) return;
    if (s.state === "stopped") {
      el.innerHTML = `<div class="refresh-row"><strong>Report stopped</strong></div>`;
      return;
    }
    const mins = Math.floor((s.elapsed || 0) / 60), secs = String((s.elapsed || 0) % 60).padStart(2, "0");
    el.innerHTML = `
      <div class="refresh-row">
        <strong>${s.state === "error" ? "Report failed" : `Step ${s.step_index + 1} of ${s.steps}: ${escapeHtml(s.step)}`}</strong>
        <span class="job-meta"><span class="muted">${running ? `${mins}:${secs}` : ""}</span>
          ${running ? `<button class="btn btn-quiet" type="button" data-stop-agent>Stop</button>` : ""}</span>
      </div>
      <div class="progress"><span style="width:${running ? ((s.step_index + 0.5) / s.steps) * 100 : 100}%"></span></div>
      <div class="muted refresh-msg">${escapeHtml(s.message || "")}</div>`;
  }

  // poll the agent until it stops; onUpdate gets every status, onDone the finished report id
  function watchAgent(el, { onDone, onUpdate } = {}) {
    clearTimeout(pollTimer);
    el.onclick = async (e) => {
      if (!e.target.closest("[data-stop-agent]")) return;
      e.target.disabled = true;
      await api("/api/agent/stop", {}).catch(() => {});
    };
    const tick = async () => {
      try {
        const s = await api("/api/agent");
        renderJob(el, s);
        onUpdate?.(s);
        if (s.state === "running") pollTimer = setTimeout(tick, POLL_MS);
        else if (s.state === "done") onDone?.(s);
      } catch (err) { pollTimer = setTimeout(tick, POLL_MS * 2); }
    };
    tick();
  }

  // ---------- report pieces ----------
  function newsList(items) {
    if (!items?.length) return `<p class="muted">No recent headlines found.</p>`;
    return `<ul class="news">${items.map((n) => `
      <li><a href="${escapeHtml(safeUrl(n.link))}" target="_blank" rel="noopener noreferrer">${escapeHtml(n.title)}</a>
        <span class="muted">${escapeHtml(n.publisher || "")}${n.published ? " · " + escapeHtml(fmtDay(n.published)) : ""}</span></li>`).join("")}</ul>`;
  }

  function reportHead(r) {
    return `<div class="report-head">
      <div><h2>${escapeHtml(r.title)}</h2>
        <p class="muted">${escapeHtml(fmtWhen(r.created_at))} · written by ${escapeHtml(r.model)} running locally</p></div>
      <button class="btn btn-quiet" type="button" data-delete-report="${r.id}">Delete</button>
    </div>`;
  }

  const disclaimer = `<p class="muted report-note">Generated by a local language model from Yahoo prices, public news feeds and this app's price model. It can be wrong or miss context. Not investment advice.</p>`;

  function portfolioReport(r) {
    const d = r.data, sim = d.simulation, p = sim.percentiles;
    const change = (p["50"] / sim.invested - 1) * 100;
    const rows = d.holdings.map((h) => `
      <tr>
        <td class="ticker"><a href="/insights/${encodeURIComponent(h.ticker)}" title="${escapeHtml(h.name || "")}">${escapeHtml(h.ticker)}</a></td>
        <td class="num">${h.weight.toFixed(1)}%</td>
        <td class="num hide-sm">${fmtPrice(h.stats?.price ?? h.prediction.price)}</td>
        <td class="num ${tone(h.stats?.return_1m)}">${fmtPct(h.stats?.return_1m)}</td>
        <td class="num hide-sm ${tone(h.stats?.return_3m)}">${fmtPct(h.stats?.return_3m)}</td>
        <td class="num hide-md ${tone(h.stats?.vs_ma200)}">${fmtPct(h.stats?.vs_ma200)}</td>
        <td class="num hide-md">${h.rank ? Math.round(h.rank.trend) : "–"}</td>
        <td class="num ${tone(h.prediction.pred_return)}">${fmtPct(h.prediction.pred_return)}</td>
      </tr>`).join("");
    const briefs = Object.entries(r.briefs_html || {});
    const skipped = d.skipped?.length
      ? `<p class="muted">Not modeled: ${d.skipped.map((s) => `${escapeHtml(s.ticker)} (${escapeHtml(s.reason)})`).join(", ")}</p>` : "";
    return `${reportHead(r)}
      <section class="stats report-stats">
        <div class="stat"><div class="stat-label">Value today</div><div class="stat-value">${fmtMoney(sim.invested)}</div></div>
        <div class="stat"><div class="stat-label">Median in 30 days</div><div class="stat-value">${fmtMoney(p["50"])} <small class="${tone(change)}">${fmtPct(change)}</small></div></div>
        <div class="stat"><div class="stat-label">Likely range (10th–90th)</div><div class="stat-value stat-range">${fmtMoney(p["10"])} – ${fmtMoney(p["90"])}</div></div>
        <div class="stat"><div class="stat-label">Chance of a loss</div><div class="stat-value">${Math.round(sim.prob_loss * 100)}%</div></div>
      </section>
      <p class="muted report-note">From ${sim.simulations.toLocaleString()} Monte Carlo simulations of the price model's 30-day forecasts.</p>
      <div class="prose report-prose">${r.html}</div>
      <h3 class="report-sub">Holdings</h3>
      <div class="table-wrap"><table class="stock-table">
        <thead><tr><th>Ticker</th><th class="num">Weight</th><th class="num hide-sm">Price</th><th class="num">1 month</th>
          <th class="num hide-sm">3 months</th><th class="num hide-md">vs 200-day</th><th class="num hide-md">Trend score</th><th class="num">30-day forecast</th></tr></thead>
        <tbody>${rows}</tbody></table></div>
      ${skipped}
      ${briefs.length ? `<h3 class="report-sub">Holding briefs</h3>${briefs.map(([t, html]) => `<details class="fold"><summary>${escapeHtml(t)}</summary><div class="prose">${html}</div></details>`).join("")}` : ""}
      <h3 class="report-sub">Sources</h3>
      ${Object.entries(d.news).map(([t, items]) => `<details class="fold"><summary>${escapeHtml(t)} <span class="muted">${items.length} headlines</span></summary>${newsList(items)}</details>`).join("")}
      ${disclaimer}`;
  }

  function stockReport(r) {
    return `${reportHead(r)}
      <div class="prose report-prose">${r.html}</div>
      <h3 class="report-sub">Sources</h3>${newsList(r.data.news)}
      ${disclaimer}`;
  }

  const renderReport = (r) => r.kind === "portfolio" ? portfolioReport(r) : stockReport(r);

  return { fmtMoney, fmtPrice, fmtPct, fmtCompact, fmtWhen, fmtDay, tone, escapeHtml, errorText, safeUrl, api, watchAgent, renderJob, renderReport, newsList };
})();
